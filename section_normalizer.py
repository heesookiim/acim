def _to_int_chapter(chapter):
    if chapter is None:
        return None
    try:
        return int(chapter)
    except (TypeError, ValueError):
        return None


def clean_section_title(title):
    if not title:
        return None
    t = str(title).strip()
    t = re.sub(r'^(제?\d+장\s+|[IVXLC]+(?:\.|\))?\s+|\d+(?:\.|\))?\s+)', '', t)
    t = re.sub(r'\s+\d+$', '', t)
    t = re.sub(r'[\xa0\s]+', ' ', t).strip()
    return t or None


def canonicalize_section(chapter, section_title):
    cleaned = clean_section_title(section_title)
    if not cleaned:
        return None

    ch = _to_int_chapter(chapter)
    if ch is not None:
        chapter_aliases = SECTION_ALIASES_BY_CHAPTER.get(ch, {})
        if cleaned in chapter_aliases:
            return chapter_aliases[cleaned]

    return GLOBAL_SECTION_ALIASES.get(cleaned, cleaned)


def get_section_id(chapter, canonical_section):
    if not canonical_section:
        return None

    ch = _to_int_chapter(chapter)
    if ch is None:
        return None

    anchors = SECTION_ANCHORS_BY_CHAPTER.get(ch)
    if not anchors:
        return None

    try:
        idx = anchors.index(canonical_section) + 1
    except ValueError:
        return None

    return f"ch{ch:02d}_sec{idx:02d}"
